# _embed_spv.py - compile the gpuwarp .comp shaders and embed them as C
# arrays in nr_gpuwarp_spv.h (the layer DLL loads from arbitrary game
# dirs - SPIR-V must travel inside the binary, not as side files).
#
# Usage: python _embed_spv.py          (run from this dir)
# Writes nr_gpuwarp_spv.h next to the .comp files.
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GLSLC = os.path.join(os.environ.get("VULKAN_SDK", r"C:\VulkanSDK\1.4.357.0"),
                     "Bin", "glslc.exe")
SHADERS = ["gpuwarp_ds", "gpuwarp_match", "gpuwarp_compose"]
OUT = os.path.join(HERE, "nr_gpuwarp_spv.h")


def words(path):
    data = open(path, "rb").read()
    assert len(data) % 4 == 0, path
    return [int.from_bytes(data[i:i + 4], "little")
            for i in range(0, len(data), 4)]


def main():
    lines = [
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* GENERATED by shaders/_embed_spv.py - do not edit. "
        "Regenerate via _embed_spv.cmd (glslc). */",
        "#ifndef NR_GPUWARP_SPV_H",
        "#define NR_GPUWARP_SPV_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    for name in SHADERS:
        src = os.path.join(HERE, name + ".comp")
        spv = os.path.join(HERE, name + ".spv")
        r = subprocess.run([GLSLC, "-O", "--target-env=vulkan1.0",
                            "-o", spv, src], capture_output=True, text=True)
        if r.returncode != 0:
            sys.stderr.write(r.stdout + r.stderr)
            raise SystemExit("glslc failed for %s" % src)
        ws = words(spv)
        lines.append("static const uint32_t %s_spv[] = {" % name)
        for i in range(0, len(ws), 8):
            lines.append("    " + ", ".join("0x%08xu" % w for w in ws[i:i + 8]) + ",")
        lines.append("};")
        lines.append("#define %s_spv_bytes %d" % (name, len(ws) * 4))
        lines.append("")
    lines.append("#endif /* NR_GPUWARP_SPV_H */")
    open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
    print("wrote %s (%d shaders)" % (OUT, len(SHADERS)))


if __name__ == "__main__":
    main()
